package dev.mixeddeno.core

import com.google.gson.JsonArray
import com.google.gson.JsonObject
import dev.mixeddeno.core.Json.arr
import dev.mixeddeno.core.Json.obj
import dev.mixeddeno.core.Json.str
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.StandardCopyOption
import kotlin.io.path.exists
import kotlin.io.path.isRegularFile
import kotlin.io.path.name

data class Problem(val file: String, val specifier: String, val message: String)

class GenerationResult(
  val scopes: List<Scope>,
  /** folders with deno.json + package.json -> their Deno-only files (excluded from that folder's tsconfig.json) */
  val dualSplits: Map<Path, List<Path>>,
  val written: List<Path>,
  val problems: List<Problem>,
  val externalRoots: Set<Path>,
  val log: List<String>,
)

/**
 * Generates, for every Deno scope, a `tsconfig.deno.json` that gives the stock TypeScript service
 * Deno globals, the import map (as `paths`), and real files for every `jsr:`/`npm:`/`https:` module.
 * Remote modules are mirrored from the Deno cache (which stores them under hashed names) into
 * `<root>/.deno-types/remote/<host>/<path>` so they keep their URL layout and file extension.
 *
 * For Deno scopes that WEB scopes import from (e.g. `shared`), files are split into
 * universal (web-reachable, no Deno APIs) -> `tsconfig.universal.json` and Deno-only.
 */
class Generator(private val root: Path, private val deno: DenoCli) {
  private val log = mutableListOf<String>()
  private val written = mutableListOf<Path>()
  private val problems = mutableListOf<Problem>()
  private val externalRoots = linkedSetOf<Path>()
  private val dualSplits = linkedMapOf<Path, List<Path>>()
  private val typesDir = root.resolve(OUT_DIR)
  private val sourceCache = HashMap<Path, String>()

  companion object {
    const val OUT_DIR = ".deno-types"
    const val DENO_TSCONFIG = "tsconfig.deno.json"
    const val UNIVERSAL_TSCONFIG = "tsconfig.universal.json"
    const val MARKER = "Generated by Mixed Deno Types. Do not edit, regenerate instead."
    private val TS_EXT = listOf("", ".ts", ".tsx", ".d.ts", ".js", ".mjs", "/mod.ts", "/index.ts", "/index.tsx", "/index.js")

    fun fingerprint(root: Path): String {
      val ws = Workspace.scan(root)
      val sb = StringBuilder()
      for (s in ws.scopes) {
        sb.append(s).append(s.importMap.entries).append('\n')
        if (s.kind == ScopeKind.DENO) {
          val specs = sortedSetOf<String>()
          for (f in s.files) runCatching { ImportScanner.scan(Files.readString(f)) }.getOrNull()
            ?.filter { !ImportScanner.isRelative(it) }?.let { specs += it }
          sb.append(specs).append('\n')
        }
      }
      return sb.toString().hashCode().toString(16)
    }
  }

  private fun read(f: Path): String = sourceCache.getOrPut(f) { runCatching { Files.readString(f) }.getOrDefault("") }
  private fun rel(from: Path, to: Path): String {
    val r = from.relativize(to).toString().replace('\\', '/')
    return if (r.startsWith("../") || r.startsWith("/")) r else "./$r"
  }
  private fun relRoot(p: Path) = root.relativize(p).toString().replace('\\', '/')

  private fun existing(p: Path): Path? {
    for (ext in TS_EXT) {
      val c = Path.of(p.toString() + ext)
      if (c.isRegularFile()) return c
    }
    return null
  }

  // ---------------------------------------------------------------- per-file resolution inside a Deno scope

  sealed interface Res
  data class FileRes(val path: Path) : Res
  data class ExtRes(val specifier: String) : Res
  data object Missing : Res
  /** Bare import served by package.json / node_modules of a folder that has both deno.json and package.json. */
  data object PackageRes : Res

  private fun resolveDeno(scope: Scope, from: Path, spec: String): Res {
    if (ImportScanner.isRelative(spec)) return existing(from.parent.resolve(spec).normalize())?.let { FileRes(it) } ?: Missing
    if (ImportScanner.isExternal(spec) || ImportScanner.isNode(spec)) return ExtRes(spec)
    return when (val t = scope.importMap.resolve(spec)) {
      is ImportMap.External -> ExtRes(t.specifier)
      is ImportMap.Local -> existing(t.path)?.let { FileRes(it) } ?: Missing
      null -> if (scope.isPackageImport(spec)) PackageRes else Missing
    }
  }

  // ---------------------------------------------------------------- main

  fun run(): GenerationResult {
    val ws = Workspace.scan(root)
    workspace = ws
    val denoScopes = ws.scopes.filter { it.kind == ScopeKind.DENO }
    log += "Scopes: " + ws.scopes.joinToString { "${it.kind.name.lowercase()} ${relRoot(it.dir).ifEmpty { "." }}" }
    if (denoScopes.isEmpty()) return GenerationResult(ws.scopes, dualSplits, written, problems, externalRoots, log)

    Files.createDirectories(typesDir)
    writeText(typesDir.resolve(".gitignore"), "*\n")
    val denoDts = typesDir.resolve("deno.d.ts")
    if (!denoDts.exists() || Files.size(denoDts) == 0L || Files.getLastModifiedTime(denoDts).toMillis() < System.currentTimeMillis() - 86_400_000L) {
      writeText(denoDts, "// $MARKER\n" + deno.types())
    }
    val cache = deno.cacheInfo()
    log += "Deno cache: ${cache.str("denoDir")}"

    val universalByScope = classifyShared(ws)

    for (scope in denoScopes) {
      try {
        generateScope(ws, scope, denoDts, universalByScope[scope].orEmpty())
      } catch (e: Exception) {
        log += "ERROR ${relRoot(scope.dir)}: ${e.message}"
        problems += Problem(scope.config.toString(), "", "Type generation failed: ${e.message}")
      }
    }
    writeReport(ws)
    return GenerationResult(ws.scopes, dualSplits, written, problems, externalRoots, log)
  }

  private fun generateScope(ws: Workspace, scope: Scope, denoDts: Path, universal: Set<Path>) {
    // 1. Walk the scope's own files plus anything reachable through the import map (e.g. ../shared).
    //    Like Deno, each file's bare specifiers resolve with the import map of its nearest deno.json.
    val visited = linkedSetOf<Path>()
    val denoFiles = if (scope.isDual) dualDenoFiles(scope) else scope.files.filter { !it.name.endsWith(".d.ts") }
    val queue = ArrayDeque(denoFiles)
    val bareToExternal = linkedMapOf<String, String>()   // specifier as written -> full external specifier
    val bareFile = HashMap<String, Path>()
    var usesNode = false
    val owners = linkedSetOf(scope)
    while (queue.isNotEmpty()) {
      val f = queue.removeFirst()
      if (!visited.add(f)) continue
      val owner = ws.scopeOf(f)?.takeIf { it.kind == ScopeKind.DENO } ?: scope
      owners.add(owner)
      for (spec in ImportScanner.scan(read(f))) {
        when (val r = resolveDeno(owner, f, spec)) {
          is FileRes -> if (r.path.toString().matches(Regex(".*\\.(m?ts|tsx|m?js|jsx)$")) && !r.path.startsWith(scope.dir.resolve("node_modules"))) queue.add(r.path)
          is ExtRes -> {
            if (ImportScanner.isNode(r.specifier)) usesNode = true else { bareToExternal[spec] = r.specifier; bareFile.putIfAbsent(spec, f) }
          }
          PackageRes -> {}
          Missing -> if (!ImportScanner.isRelative(spec)) {
            problems += Problem(f.toString(), spec, "'$spec' is not in the import map of ${relRoot(owner.config!!)}")
          }
        }
      }
    }

    // 2. Ask Deno for the module graph of every external specifier.
    val externals = bareToExternal.values.toSortedSet()
    if (usesNode) externals += "npm:@types/node"
    val graph = buildGraph(scope, externals)

    // 3. Map specifiers to real files.
    val paths = JsonObject()
    fun put(key: String, target: String) { if (!paths.has(key)) paths.add(key, Json.array(listOf(target))) }

    for (o in owners) for ((prefix, dir) in o.importMap.localPrefixes()) put("$prefix*", rel(scope.dir, dir) + "/*")
    for ((key, value) in scope.importMap.entries) { // exact local aliases
      if (!key.endsWith("/") && !ImportScanner.isExternal(value) && !ImportScanner.isNode(value)) {
        existing(scope.importMap.baseDir.resolve(value).normalize())?.let { put(key, rel(scope.dir, it)) }
      }
    }
    for ((bare, ext) in bareToExternal) {
      val target = graph.fileFor(ext)
      if (target != null) put(bare, target.toTarget(scope))
      else problems += Problem(bareFile[bare].toString(), bare, "No types for '$bare' ($ext): ${graph.errors[ext] ?: "deno could not load it (run deno install, check network)"}")
    }
    for ((spec, resolved) in graph.innerSpecifiers) graph.fileFor(resolved)?.let { put(spec, it.toTarget(scope)) }
    for ((name, dir) in graph.npmPackageDirs) {
      put(name, Target(dir).toTarget(scope))
      put("$name/*", Target(dir).toTarget(scope) + "/*")
    }

    // 4. tsconfig.deno.json
    val userCo = scope.denoJson?.obj("compilerOptions")
    val co = JsonObject().apply {
      addProperty("target", "esnext")
      addProperty("module", "esnext")
      addProperty("moduleResolution", "bundler")
      add("lib", Json.array(denoLibs(userCo)))
      add("types", JsonArray())
      addProperty("allowImportingTsExtensions", true)
      addProperty("noEmit", true)
      addProperty("skipLibCheck", true)
      addProperty("esModuleInterop", true)
      addProperty("isolatedModules", true)
      addProperty("strict", userCo?.get("strict")?.asBoolean ?: true)
      userCo?.str("jsx")?.let { addProperty("jsx", it) }
      userCo?.str("jsxImportSource")?.let { addProperty("jsxImportSource", it) }
      userCo?.str("jsxFactory")?.let { addProperty("jsxFactory", it) }
      add("paths", paths)
    }
    val include = mutableListOf("**/*.ts", "**/*.tsx", "**/*.mts", rel(scope.dir, denoDts))
    graph.nodeTypes?.let { include += it.toTarget(scope) }
    val exclude = mutableListOf("node_modules", "**/node_modules")
    exclude += universal.map { rel(scope.dir, it) }
    exclude += ws.scopes.filter { it !== scope && it.dir.startsWith(scope.dir) }.map { rel(scope.dir, it.dir) }
    val tsconfig = JsonObject().apply {
      addProperty("//", MARKER)
      add("compilerOptions", co)
      if (scope.isDual) {
        // only the Deno files; the rest of the folder is typed by its own tsconfig.json (package.json side)
        val files = denoFiles.map { rel(scope.dir, it) } + rel(scope.dir, denoDts) + listOfNotNull(graph.nodeTypes?.toTarget(scope))
        add("files", Json.array(files))
      } else {
        add("include", Json.array(include))
        add("exclude", Json.array(exclude))
      }
    }
    if (scope.isDual) {
      dualSplits[scope.dir] = denoFiles
      log += "${relRoot(scope.dir).ifEmpty { "." }}: deno.json + package.json, ${denoFiles.size} Deno file(s), ${scope.files.size - denoFiles.size} package.json file(s)"
    }
    if (Json.write(scope.dir.resolve(DENO_TSCONFIG), tsconfig)) written.add(scope.dir.resolve(DENO_TSCONFIG))

    // 5. tsconfig.universal.json for files shared with browser code
    val uniFile = scope.dir.resolve(UNIVERSAL_TSCONFIG)
    if (universal.isNotEmpty()) {
      val uniPaths = JsonObject()
      for ((prefix, dir) in scope.importMap.localPrefixes()) uniPaths.add("$prefix*", Json.array(listOf(rel(scope.dir, dir) + "/*")))
      val uni = JsonObject().apply {
        addProperty("//", "$MARKER Files here are imported by browser code: no Deno APIs, no jsr:/npm: imports.")
        add("compilerOptions", JsonObject().apply {
          addProperty("target", "esnext")
          addProperty("module", "esnext")
          addProperty("moduleResolution", "bundler")
          add("lib", Json.array(listOf("esnext", "DOM", "DOM.Iterable")))
          add("types", JsonArray())
          addProperty("allowImportingTsExtensions", true)
          addProperty("noEmit", true)
          addProperty("skipLibCheck", true)
          addProperty("isolatedModules", true)
          addProperty("strict", userCo?.get("strict")?.asBoolean ?: true)
          add("paths", uniPaths)
        })
        add("files", Json.array(universal.sorted().map { rel(scope.dir, it) }))
      }
      if (Json.write(uniFile, uni)) written.add(uniFile)
    } else if (uniFile.exists() && read(uniFile).contains(MARKER)) {
      Files.delete(uniFile)
    }
    log += "${relRoot(scope.dir).ifEmpty { "." }}: ${visited.size} files, ${externals.size} external, ${paths.size()} paths" +
      (if (universal.isNotEmpty()) ", ${universal.size} universal" else "")
  }

  private fun denoLibs(co: JsonObject?): List<String> {
    val libs = linkedSetOf("esnext", "DOM", "DOM.Iterable", "DOM.AsyncIterable")
    co?.arr("lib")?.forEach { e ->
      val l = e.asString
      when {
        l.startsWith("deno.") -> {}
        l.equals("dom", true) -> libs += "DOM"
        l.startsWith("dom.", true) -> libs += "DOM." + l.substringAfter('.').replaceFirstChar { it.uppercase() }
        else -> libs += l
      }
    }
    return libs.toList()
  }

  // ---------------------------------------------------------------- deno graph -> mirrored files

  /** A file target: either inside the mirror, or an npm package (dir) on disk. */
  private data class Target(val path: Path) {
    fun toTarget(scope: Scope): String =
      if (path.startsWith(scope.dir.root) && !path.startsWith(System.getProperty("user.home") + "/.cache"))
        scope.dir.relativize(path).toString().replace('\\', '/').let { if (it.startsWith("../")) it else "./$it" }
      else path.toString()
  }

  private inner class Graph {
    val redirects = HashMap<String, String>()
    val mirrored = HashMap<String, Path>()          // https specifier -> mirrored file
    val typesOf = HashMap<String, String>()         // js module -> its types module
    val npmPackages = HashMap<String, Path>()       // name@version -> local dir
    val innerSpecifiers = linkedMapOf<String, String>()  // non-relative specifiers inside remote modules -> resolved
    val npmPackageDirs = linkedMapOf<String, Path>()
    var nodeTypes: Target? = null
    val errors = HashMap<String, String>()

    fun fileFor(spec: String, depth: Int = 0): Target? {
      if (depth > 10) return null
      redirects[spec]?.let { return fileFor(it, depth + 1) }
      typesOf[spec]?.let { return fileFor(it, depth + 1) }
      mirrored[spec]?.let { return Target(it) }
      if (spec.startsWith("npm:")) return npmTarget(spec)
      return null
    }

    lateinit var scope: Scope

    private fun npmTarget(spec: String): Target? {
      val body = spec.removePrefix("npm:").removePrefix("/")
      val name = if (body.startsWith("@")) body.split('/').take(2).joinToString("/") else body.substringBefore('/')
      val nameNoVer = name.substringBeforeLast('@').ifEmpty { name }
      val sub = body.removePrefix(name).removePrefix("/")
      val local = scope.dir.resolve("node_modules").resolve(nameNoVer)
      val dir = if (local.exists()) local
      else npmPackages.entries.firstOrNull { it.key.substringBeforeLast('@') == nameNoVer && (name == nameNoVer || it.key == name) }?.value
        ?: npmPackages.entries.firstOrNull { it.key.substringBeforeLast('@') == nameNoVer }?.value
        ?: return null
      externalRoots.add(dir)
      return Target(if (sub.isEmpty()) dir else dir.resolve(sub))
    }
  }

  private fun Path.toRealPathOrSelf(): Path = runCatching { toRealPath() }.getOrDefault(this)

  private fun buildGraph(scope: Scope, externals: Set<String>): Graph {
    val g = Graph().also { it.scope = scope }
    if (externals.isEmpty()) return g
    val entryDir = Files.createTempDirectory("mixed-deno-types")
    try {
      val entry = entryDir.resolve("entry.ts")
      val infos = mutableListOf<JsonObject>()
      Files.writeString(entry, externals.joinToString("") { "import \"$it\";\n" })
      try {
        infos += deno.graph(entry)
      } catch (e: DenoException) {
        // isolate the failing specifier(s)
        for (spec in externals) {
          Files.writeString(entry, "import \"$spec\";\n")
          try { infos += deno.graph(entry) } catch (e2: DenoException) {
            problems += Problem(scope.config.toString(), spec, "deno could not load '$spec': ${e2.message?.lineSequence()?.lastOrNull { it.isNotBlank() }}")
          }
        }
      }
      for (info in infos) ingest(g, info)
    } finally {
      entryDir.toFile().deleteRecursively()
    }
    g.nodeTypes = g.npmPackages.entries.firstOrNull { it.key.startsWith("@types/node@") }?.value?.resolve("index.d.ts")?.let { Target(it) }
    return g
  }

  private fun ingest(g: Graph, info: JsonObject) {
    info.obj("redirects")?.entrySet()?.forEach { (k, v) -> g.redirects[k] = v.asString }
    info.obj("npmPackages")?.entrySet()?.forEach { (k, v) ->
      v.asJsonObject.str("localPath")?.let { p ->
        val dir = Path.of(p)
        g.npmPackages[k] = dir
        val name = v.asJsonObject.str("name") ?: k.substringBeforeLast('@')
        if (name != "@types/node" && !g.npmPackageDirs.containsKey(name)) g.npmPackageDirs[name] = dir
        externalRoots.add(dir)
      }
    }
    for (m in info.arr("modules") ?: JsonArray()) {
      val mod = m.asJsonObject
      val spec = mod.str("specifier") ?: continue
      mod.str("error")?.let { err ->
        g.errors[spec] = err
        g.redirects.entries.filter { it.value == spec }.forEach { g.errors[it.key] = err }
      }
      if (spec.startsWith("https://") || spec.startsWith("http://")) {
        val local = mod.str("local")?.let { Path.of(it) }
        if (local != null && local.exists()) g.mirrored[spec] = mirror(spec, local, mod.str("mediaType"))
        mod.obj("typesDependency")?.obj("dependency")?.str("specifier")?.let { g.typesOf[spec] = it }
        for (d in mod.arr("dependencies") ?: JsonArray()) {
          val dep = d.asJsonObject
          val written = dep.str("specifier") ?: continue
          if (ImportScanner.isRelative(written) || ImportScanner.isNode(written)) continue
          val resolved = dep.obj("code")?.str("specifier") ?: dep.obj("type")?.str("specifier") ?: written
          g.innerSpecifiers.putIfAbsent(written, resolved)
        }
      }
    }
  }

  private fun mirror(url: String, local: Path, mediaType: String?): Path {
    val u = java.net.URI(url)
    var path = (u.host + (if (u.port > 0) "_${u.port}" else "") + u.path).replace(Regex("[^A-Za-z0-9._@/+-]"), "_")
    val ext = when (mediaType) {
      "TypeScript" -> ".ts"; "Dts" -> ".d.ts"; "Dmts" -> ".d.mts"; "Mts" -> ".mts"; "TSX" -> ".tsx"
      "JavaScript" -> ".js"; "Mjs" -> ".mjs"; "JSX" -> ".jsx"; "Json" -> ".json"; else -> ""
    }
    if (ext.isNotEmpty() && !path.endsWith(ext) && !(ext == ".ts" && path.endsWith(".mts"))) {
      if (!Regex(".*\\.(d\\.)?[cm]?[jt]sx?$").matches(path)) path += ext
    }
    val dest = typesDir.resolve("remote").resolve(path)
    if (!dest.exists() || Files.size(dest) != Files.size(local)) {
      Files.createDirectories(dest.parent)
      Files.copy(local, dest, StandardCopyOption.REPLACE_EXISTING)
    }
    return dest
  }

  // ---------------------------------------------------------------- shared code classification

  /**
   * For each Deno scope imported by WEB scopes: universal = files reachable from web imports that do
   * not (transitively) use Deno APIs or jsr:/npm:/https:/node: imports. Web imports of Deno-only files
   * are reported.
   */
  private fun classifyShared(ws: Workspace): Map<Scope, Set<Path>> {
    val result = HashMap<Scope, MutableSet<Path>>()
    for (web in ws.scopes.filter { it.kind == ScopeKind.WEB || it.isDual }) {
      val resolver = if (web.kind == ScopeKind.WEB) WebResolver(web)
        else web.dir.resolve("tsconfig.json").takeIf { it.exists() }?.let { WebResolver(web, it) }
      val webFiles = if (web.isDual) (web.files - dualDenoFiles(web).toSet()).filter { !it.name.endsWith(".d.ts") } else web.files
      for (f in webFiles) {
        for (spec in ImportScanner.scan(read(f))) {
          if (ImportScanner.isRelative(spec)) {
            // relative import escaping the web scope
            val p = existing(f.parent.resolve(spec).normalize()) ?: continue
            if (p.startsWith(web.dir) && !web.isDual) continue
            checkWebImport(ws, f, spec, p, result) { sc, file, st -> denoReason(sc, file, st) }
          } else {
            val p = resolver?.resolve(spec)?.firstNotNullOfOrNull { existing(it) } ?: continue
            checkWebImport(ws, f, spec, p, result) { sc, file, st -> denoReason(sc, file, st) }
          }
        }
      }
    }
    // close universal sets over their own local imports
    for ((scope, set) in result) {
      val queue = ArrayDeque(set)
      while (queue.isNotEmpty()) {
        val f = queue.removeFirst()
        for (spec in ImportScanner.scan(read(f))) {
          val r = resolveDeno(scope, f, spec) as? FileRes ?: continue
          if (r.path.startsWith(scope.dir) && denoReason(scope, r.path, linkedSetOf()) == null && set.add(r.path)) queue.add(r.path)
        }
      }
    }
    return result
  }

  private val denoOnlyCache = HashMap<Path, String?>()

  /** Why [f] can only run on Deno (Deno APIs, jsr:/https:/npm: specifiers, or importing such a file); null if it is portable. */
  fun denoReason(scope: Scope, f: Path, stack: MutableSet<Path> = linkedSetOf()): String? {
    if (f in denoOnlyCache) return denoOnlyCache[f]
    if (!stack.add(f)) return null
    val owner = workspace?.scopeOf(f)?.takeIf { it.kind == ScopeKind.DENO } ?: scope
    val src = read(f)
    var reason: String? = if (ImportScanner.usesDenoGlobal(src)) "uses Deno.* APIs" else null
    if (reason == null) for (spec in ImportScanner.scan(src)) {
      when (val r = resolveDeno(owner, f, spec)) {
        is ExtRes -> if (!ImportScanner.isNode(r.specifier) || !owner.isDual) reason = "imports '$spec' (${r.specifier})"
        is FileRes -> denoReason(owner, r.path, stack)?.let { reason = "imports '$spec', which $it" }
        Missing, PackageRes -> {}
      }
      if (reason != null) break
    }
    stack.remove(f)
    denoOnlyCache[f] = reason
    return reason
  }

  /** Deno files of a dual folder: not .tsx/.jsx and Deno-only. Everything else there belongs to package.json / tsconfig.json. */
  fun dualDenoFiles(scope: Scope): List<Path> = scope.files.filter {
    val n = it.name
    !n.endsWith(".tsx") && !n.endsWith(".jsx") && !n.endsWith(".d.ts") && denoReason(scope, it) != null
  }

  private var workspace: Workspace? = null

  private fun checkWebImport(
    ws: Workspace, from: Path, spec: String, target: Path,
    result: HashMap<Scope, MutableSet<Path>>, denoReason: (Scope, Path, MutableSet<Path>) -> String?,
  ) {
    val owner = ws.scopeOf(target) ?: return
    if (owner.kind != ScopeKind.DENO) return
    val reason = denoReason(owner, target, linkedSetOf())
    if (reason == null) { if (!owner.isDual) result.getOrPut(owner) { linkedSetOf() }.add(target) }
    else problems += Problem(from.toString(), spec, "Browser code imports Deno-only module ${relRoot(target)}: it $reason")
  }

  // ---------------------------------------------------------------- output

  private fun writeText(file: Path, text: String) {
    if (file.exists() && Files.readString(file) == text) return
    Files.createDirectories(file.parent)
    Files.writeString(file, text)
    written.add(file)
  }

  private fun writeReport(ws: Workspace) {
    val report = JsonObject().apply {
      add("scopes", JsonArray().also { a ->
        ws.scopes.forEach { s -> a.add(JsonObject().apply { addProperty("kind", s.kind.name); addProperty("dir", relRoot(s.dir)); addProperty("files", s.files.size) }) }
      })
      add("problems", JsonArray().also { a ->
        problems.distinct().also { problems.clear(); problems.addAll(it) }.forEach { p -> a.add(JsonObject().apply { addProperty("file", relRoot(Path.of(p.file))); addProperty("specifier", p.specifier); addProperty("message", p.message) }) }
      })
      add("log", Json.array(log))
    }
    Json.write(typesDir.resolve("report.json"), report)
  }
}
